async function seedMockProducts() {
  await mongoose.connect(config.mongodbUri);
  console.log("Connected to MongoDB database for seeding mock products...\n");

  let totalAdded = 0;
  const categoriesList = Object.keys(mockProductsByCategory);

  for (const category of categoriesList) {
    const products = mockProductsByCategory[category];
    console.log(`📦 Seeding 5 products for category: "${category}"...`);

    for (const p of products) {
      const fullDoc = {
        name: p.name,
        slug: p.slug,
        brand: p.brand || "AquaPets",
        category,
        description: p.description,
        fullDescription: `${p.name} by ${p.brand}. High quality aquarium supply thoroughly tested for aquatic safety and performance. ${p.description}`,
        price: p.price,
        originalPrice: p.originalPrice || Math.round(p.price * 1.3),
        discount: p.discount || 20,
        rating: p.rating || 4.8,
        reviewCount: p.reviewCount || 25,
        stock: p.stock || 30,
        weightKg: p.weightKg || 0.5,
        badge: p.badge || "",
        images: p.images || [`/categories/${category}.jpg`],
        tags: p.tags || [category, "aquarium", "aquapets"],
        isFeatured: false,
        isStarterKit: false,
        isOffer: Boolean(p.discount && p.discount >= 25),
        specifications: [
          { label: "Brand", value: p.brand || "AquaPets" },
          { label: "Category", value: category.replace(/-/g, " ").toUpperCase() },
          { label: "Weight", value: `${p.weightKg || 0.5} kg` },
          { label: "Suitability", value: "Freshwater & Marine Aquariums" },
        ],
      };

      await Product.findOneAndUpdate(
        { slug: p.slug },
        { $set: fullDoc },
        { upsert: true, returnDocument: "after" }
      );
      totalAdded++;
    }
  }

  console.log(`\n🎉 Successfully upserted ${totalAdded} mock products across ${categoriesList.length} categories!`);

  const distinctCats = await Product.distinct("category");
  console.log("\n📊 Verification - Categories now present in database:");
  for (const cat of distinctCats) {
    const count = await Product.countDocuments({ category: cat });
    console.log(` - ${cat}: ${count} products`);
  }

  const grandTotal = await Product.countDocuments();
  console.log(`\n✨ Grand Total Products in Database: ${grandTotal}`);

  await mongoose.disconnect();
}

seedMockProducts().catch((err) => {
  console.error("Error seeding mock products:", err);
  process.exit(1);
});
